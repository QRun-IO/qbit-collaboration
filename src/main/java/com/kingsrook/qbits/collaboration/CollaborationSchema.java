package com.kingsrook.qbits.collaboration;


import java.util.ArrayList;
import java.util.List;
import com.kingsrook.qbits.collaboration.model.CollaborationTables;
import com.kingsrook.qqq.backend.core.model.metadata.fields.QFieldMetaData;
import com.kingsrook.qqq.backend.core.model.metadata.tables.QTableMetaData;
import com.kingsrook.qqq.backend.core.model.metadata.tables.UniqueKey;


/*******************************************************************************
 ** PostgreSQL DDL generated from the same fields and unique keys as QQQ metadata.
 ** Hosts apply it through their migration tooling; this class never executes DDL.
 *******************************************************************************/
public final class CollaborationSchema
{
   /*******************************************************************************
    ** Utility class.
    *******************************************************************************/
   private CollaborationSchema()
   {
   }



   /*******************************************************************************
    ** Create tables and unique indexes using QQQ's inferred snake_case columns.
    *******************************************************************************/
   public static String postgresScript(CollaborationQBitConfig config)
   {
      List<String> statements = new ArrayList<>();
      for(QTableMetaData table : CollaborationTables.tables(config))
      {
         List<String> columns = new ArrayList<>();
         for(QFieldMetaData field : table.getFields().values())
         {
            String type = field.getName().equals(table.getPrimaryKeyField()) ? "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : sqlType(field);
            columns.add("   " + field.getBackendName() + " " + type + (Boolean.TRUE.equals(field.getIsRequired()) ? " NOT NULL" : ""));
         }
         statements.add("CREATE TABLE IF NOT EXISTS " + table.getName() + " (\n" + String.join(",\n", columns) + "\n)");
         int index = 0;
         for(UniqueKey key : table.getUniqueKeys())
         {
            index++;
            List<String> names = key.getFieldNames().stream().map(name -> table.getField(name).getBackendName()).toList();
            statements.add("CREATE UNIQUE INDEX IF NOT EXISTS uq_" + table.getName() + "_" + index + " ON " + table.getName() + " (" + String.join(", ", names) + ")"
               + (key.getFieldNames().contains("recordId") ? " NULLS NOT DISTINCT" : ""));
         }
      }
      return (String.join(";\n", statements) + ";\n");
   }



   /*******************************************************************************
    ** Supported PostgreSQL types; fail explicitly for unsupported metadata.
    *******************************************************************************/
   private static String sqlType(QFieldMetaData field)
   {
      return (switch(field.getType())
      {
         case STRING -> "VARCHAR(" + (field.getMaxLength() == null ? 255 : field.getMaxLength()) + ")";
         case TEXT -> "TEXT";
         case INTEGER -> "INTEGER";
         case BOOLEAN -> "BOOLEAN";
         case DATE_TIME -> "TIMESTAMPTZ";
         case DATE -> "DATE";
         case DECIMAL -> "NUMERIC";
         default -> throw new IllegalArgumentException("Unsupported schema type: " + field.getType());
      });
   }
}
