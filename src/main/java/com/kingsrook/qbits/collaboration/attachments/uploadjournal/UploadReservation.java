package com.kingsrook.qbits.collaboration.attachments.uploadjournal;


import java.time.Instant;


/*******************************************************************************
 ** Immutable write reservation: an exclusive, fenced lease on one journal row.
 ** Every mutating journal call re-checks the token, fence and expiry under a row
 ** lock, so a holder that lost its lease cannot act. The token is generated by
 ** the journal, is never persisted outside the journal row, never printed, and
 ** is not accepted from clients. The snapshot is as of the grant.
 *******************************************************************************/
public final class UploadReservation
{
   private final UploadEntry entry;
   private final String leaseToken;
   private final Long fence;
   private final Instant leaseUntil;



   /*******************************************************************************
    ** Package-local; only the journal grants reservations.
    *******************************************************************************/
   UploadReservation(UploadEntry entry, String leaseToken, Long fence, Instant leaseUntil)
   {
      this.entry = entry;
      this.leaseToken = leaseToken;
      this.fence = fence;
      this.leaseUntil = leaseUntil;
   }



   /*******************************************************************************
    ** Journal row id.
    *******************************************************************************/
   public Integer journalId()
   {
      return (entry.id());
   }



   /*******************************************************************************
    ** The preserved manifest.
    *******************************************************************************/
   public UploadCandidate candidate()
   {
      return (entry.candidate());
   }



   /*******************************************************************************
    ** Journal state as of the grant; read the journal for current state.
    *******************************************************************************/
   public UploadEntry entryAtGrant()
   {
      return (entry);
   }



   /*******************************************************************************
    ** Fencing counter of this grant.
    *******************************************************************************/
   public Long fence()
   {
      return (fence);
   }



   /*******************************************************************************
    ** Lease expiry of this grant.
    *******************************************************************************/
   public Instant leaseUntil()
   {
      return (leaseUntil);
   }



   /*******************************************************************************
    ** Secret proof of ownership, visible only to the journal implementation.
    *******************************************************************************/
   String leaseToken()
   {
      return (leaseToken);
   }



   /*******************************************************************************
    ** Never prints the token.
    *******************************************************************************/
   @Override
   public String toString()
   {
      return ("UploadReservation[journalId=" + entry.id() + ", fence=" + fence + ", leaseUntil=" + leaseUntil + "]");
   }
}
