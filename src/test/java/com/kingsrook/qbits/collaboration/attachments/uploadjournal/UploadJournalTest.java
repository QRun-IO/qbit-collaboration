   /*******************************************************************************
    ** Many real connections race for one reservation; exactly one wins.
    *******************************************************************************/
   @Test
   void concurrentClaimsGrantExactlyOneReservation() throws Exception
   {
      UploadEntry prepared = journal.prepare(candidate("race"));
      List<Object> outcomes = race(8, () -> journal.reserve(prepared.id(), Duration.ofMinutes(1)));

      List<Object> winners = outcomes.stream().filter(UploadReservation.class::isInstance).toList();
      assertThat(winners).hasSize(1);
      for(Object outcome : outcomes)
      {
         if(!(outcome instanceof UploadReservation))
         {
            assertThat(outcome).isInstanceOf(UploadJournalException.class);
            assertThat(((UploadJournalException) outcome).getReason()).isIn(Reason.LEASE_HELD, Reason.BUSY);
         }
      }
      assertThat(journal.find(prepared.id()).orElseThrow().fence()).isEqualTo(1L);
   }



   /*******************************************************************************
    ** Concurrent identical prepares converge on one row; differing manifests,
    ** altered rows and reused intake keys are immutable conflicts.
    *******************************************************************************/
   @Test
   void immutableManifestAndUniqueRaceRecovery() throws Exception
   {
      UploadCandidate candidate = candidate("immutable");
      List<Object> outcomes = race(6, () -> journal.prepare(candidate));
      Set<Integer> ids = new HashSet<>();
      for(Object outcome : outcomes)
      {
         assertThat(outcome).isInstanceOf(UploadEntry.class);
         ids.add(((UploadEntry) outcome).id());
      }
      assertThat(ids).hasSize(1);
      assertThat(count("SELECT COUNT(*) FROM collaboration_upload_journal")).isEqualTo(1);
      assertThat(journal.prepare(candidate).id()).isEqualTo(ids.iterator().next());

      UploadCandidate changed = new UploadCandidate(candidate.tableName(), candidate.recordId(), "mallory", candidate.fileName(), candidate.contentType(),
         candidate.description(), candidate.sizeBytes(), candidate.sha256(), candidate.bucketName(), candidate.storageKey(), true, null, null);
      assertThatThrownBy(() -> journal.prepare(changed)).isInstanceOfSatisfying(UploadJournalException.class,
         e -> assertThat(e.getReason()).isEqualTo(Reason.IMMUTABLE_CONFLICT));

      String intake = "b".repeat(64);
      journal.prepare(withIntake(candidate("intake-a"), intake));
      assertThatThrownBy(() -> journal.prepare(withIntake(candidate("intake-b"), intake))).isInstanceOfSatisfying(UploadJournalException.class,
         e -> assertThat(e.getReason()).isEqualTo(Reason.IMMUTABLE_CONFLICT));

      try(Connection connection = DriverManager.getConnection(database.getJdbcUrl(), "sa", ""); Statement statement = connection.createStatement())
      {
         statement.execute("UPDATE collaboration_upload_journal SET file_name = 'evil.pdf' WHERE id = " + ids.iterator().next());
      }
      assertThatThrownBy(() -> journal.find(ids.iterator().next())).isInstanceOfSatisfying(UploadJournalException.class,
         e -> assertThat(e.getReason()).isEqualTo(Reason.IMMUTABLE_CONFLICT));
   }



   /*******************************************************************************
    ** COMPLETE only follows registration; a registered row recovers without a
    ** second attachment once the lifecycle callback is retried.
    *******************************************************************************/
   @Test
   void lifecycleCompletionCheckpointAndIdempotentRecovery() throws Exception
   {
      UploadReservation reservation = verified(candidate("lifecycle"));
      AtomicInteger calls = new AtomicInteger();
      assertThatThrownBy(() -> journal.complete(reservation)).isInstanceOfSatisfying(UploadJournalException.class,
         e -> assertThat(e.getReason()).isEqualTo(Reason.ILLEGAL_STATE));

      UploadEntry registered = journal.register(reservation, inserting(calls));
      assertThat(registered.state()).isEqualTo(UploadJournalState.REGISTERED);
      assertThat(journal.register(reservation, inserting(calls)).attachmentId()).isEqualTo(registered.attachmentId());
      assertThat(calls).hasValue(1);

      // The post-commit lifecycle callback failed: free the lease and recover later.
      assertThat(journal.release(reservation)).isTrue();
      UploadReservation recovery = journal.reserve(reservation.journalId(), Duration.ofMinutes(1));
      assertThat(journal.register(recovery, inserting(calls)).attachmentId()).isEqualTo(registered.attachmentId());
      assertThat(calls).hasValue(1);
      assertThat(count("SELECT COUNT(*) FROM collaboration_attachment")).isEqualTo(1);

      UploadEntry complete = journal.complete(recovery);
      assertThat(complete.state()).isEqualTo(UploadJournalState.COMPLETE);
      assertThat(complete.leaseUntil()).isNull();
      assertThat(count("SELECT COUNT(*) FROM collaboration_upload_journal WHERE lease_token IS NULL AND state = 'COMPLETE'")).isEqualTo(1);
      assertThat(journal.complete(recovery).state()).isEqualTo(UploadJournalState.COMPLETE);
      assertThat(journal.listIncomplete(10)).isEmpty();
      assertThatThrownBy(() -> journal.reserve(reservation.journalId(), Duration.ofMinutes(1))).isInstanceOfSatisfying(UploadJournalException.class,
         e -> assertThat(e.getReason()).isEqualTo(Reason.ILLEGAL_STATE));
   }



