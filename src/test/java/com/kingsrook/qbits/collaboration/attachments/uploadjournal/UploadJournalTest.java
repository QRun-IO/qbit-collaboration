   /*******************************************************************************
    ** An H2 file backend; settings are appended to the URL verbatim.
    *******************************************************************************/
   private RDBMSBackendMetaData fileBackend(String name, String file, String settings)
   {
      RDBMSBackendMetaData backend = new RDBMSBackendMetaData().withName(name).withVendor("h2").withHostName("mem").withDatabaseName(file).withUsername("sa");
      backend.setJdbcUrl("jdbc:h2:file:" + directory.resolve(file).toAbsolutePath().toString().replace('\\', '/') + ";DATABASE_TO_UPPER=FALSE;LOCK_TIMEOUT=5000" + settings);
      return (backend);
   }



   /*******************************************************************************
    ** A synthetic instance with the journal and attachment tables registered on
    ** the given backends.
    *******************************************************************************/
   private QInstance instanceFor(RDBMSBackendMetaData journalBackend, RDBMSBackendMetaData attachmentBackend)
   {
      QInstance built = new QInstance().withInstanceDefaultAuthentication(new QAuthenticationMetaData().withName("anonymous").withType(QAuthenticationType.FULLY_ANONYMOUS));
      built.addBackend(journalBackend);
      if(!attachmentBackend.getName().equals(journalBackend.getName()))
      {
         built.addBackend(attachmentBackend);
      }
      built.addTable(stand(UploadJournalTable.NAME, journalBackend));
      built.addTable(stand(CollaborationTables.ATTACHMENT, attachmentBackend));
      return (built);
   }



