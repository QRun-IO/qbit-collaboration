   /*******************************************************************************
    ** Committed PREPARED data survives a crashed lock holder and a full database
    ** shutdown and reopen; nothing uncommitted leaks.
    *******************************************************************************/
   @Test
   void preparedCandidateSurvivesCrashStyleReopen() throws Exception
   {
      UploadCandidate candidate = candidate("one");
      UploadEntry prepared = journal.prepare(candidate);
      assertThat(prepared.state()).isEqualTo(UploadJournalState.PREPARED);
      assertThat(prepared.storageState()).isEqualTo(UploadStorageState.PENDING);

      try(Connection crashing = DriverManager.getConnection(database.getJdbcUrl(), "sa", ""); Statement statement = crashing.createStatement())
      {
         crashing.setAutoCommit(false);
         statement.execute("UPDATE collaboration_upload_journal SET fence = 99 WHERE id = " + prepared.id());
         // closed with the row locked and never committed: the crash
      }
      ConnectionManager.resetConnectionProviders();
      try(Connection connection = DriverManager.getConnection(database.getJdbcUrl(), "sa", ""); Statement statement = connection.createStatement())
      {
         statement.execute("SHUTDOWN");
      }
      ConnectionManager.resetConnectionProviders();

      JdbcUploadJournal reopened = new JdbcUploadJournal(clock);
      UploadEntry found = reopened.find(prepared.id()).orElseThrow();
      assertThat(found.candidate()).isEqualTo(candidate);
      assertThat(found.state()).isEqualTo(UploadJournalState.PREPARED);
      assertThat(found.fence()).isZero();
      assertThat(reopened.listIncomplete(10)).extracting(UploadEntry::id).containsExactly(prepared.id());
      assertThat(reopened.findByLocation("bucket", "attachments/one")).isPresent();
      assertThat(reopened.reserve(prepared.id(), Duration.ofMinutes(1)).fence()).isEqualTo(1L);
   }



   /*******************************************************************************
    ** A failure after the attachment insert rolls back the insert and the
    ** checkpoint together; a clean retry then registers exactly once.
    *******************************************************************************/
   @Test
   void failedMetadataInsertRollsBackAttachmentAndCheckpoint() throws Exception
   {
      UploadReservation reservation = verified(candidate("rollback"));
      AtomicInteger calls = new AtomicInteger();
      UploadJournal.AttachmentRegistrar failing = (transaction, candidate, journalId) ->
      {
         insertAttachment(transaction, candidate);
         calls.incrementAndGet();
         throw (new IllegalStateException("simulated failure after insert"));
      };

      assertThatThrownBy(() -> journal.register(reservation, failing)).isInstanceOf(IllegalStateException.class);
      assertThat(count("SELECT COUNT(*) FROM collaboration_attachment")).isZero();
      UploadEntry afterFailure = journal.find(reservation.journalId()).orElseThrow();
      assertThat(afterFailure.state()).isEqualTo(UploadJournalState.PREPARED);
      assertThat(afterFailure.attachmentId()).isNull();
      assertThat(afterFailure.storageState()).isEqualTo(UploadStorageState.VERIFIED);

      UploadEntry registered = journal.register(reservation, inserting(calls));
      assertThat(registered.state()).isEqualTo(UploadJournalState.REGISTERED);
      assertThat(registered.attachmentId()).isNotNull();
      assertThat(count("SELECT COUNT(*) FROM collaboration_attachment")).isEqualTo(1);
      assertThat(count("SELECT COUNT(*) FROM collaboration_attachment WHERE id = " + registered.attachmentId())).isEqualTo(1);
   }



   /*******************************************************************************
    ** Unverified original storage is never registered, and the callback never runs.
    *******************************************************************************/
   @Test
   void registrationRequiresVerifiedStorage() throws Exception
   {
      UploadEntry prepared = journal.prepare(candidate("unverified"));
      UploadReservation reservation = journal.reserve(prepared.id(), Duration.ofMinutes(1));
      journal.recordStorage(reservation, UploadStorageState.UNKNOWN);
      AtomicInteger calls = new AtomicInteger();

      assertThatThrownBy(() -> journal.register(reservation, inserting(calls))).isInstanceOfSatisfying(UploadJournalException.class,
         e -> assertThat(e.getReason()).isEqualTo(Reason.STORAGE_NOT_VERIFIED));
      assertThat(calls).hasValue(0);
      assertThat(count("SELECT COUNT(*) FROM collaboration_attachment")).isZero();
      assertThatThrownBy(() -> journal.recordStorage(reservation, UploadStorageState.PENDING)).isInstanceOf(UploadJournalException.class);
      journal.recordStorage(reservation, UploadStorageState.VERIFIED);
      assertThatThrownBy(() -> journal.recordStorage(reservation, UploadStorageState.UNKNOWN)).isInstanceOfSatisfying(UploadJournalException.class,
         e -> assertThat(e.getReason()).isEqualTo(Reason.ILLEGAL_STATE));
   }



   /*******************************************************************************
    ** An expired or superseded holder cannot mutate; a newer fence takes over.
    *******************************************************************************/
   @Test
   void staleLeaseIsRejected() throws Exception
   {
      UploadEntry prepared = journal.prepare(candidate("stale"));
      UploadReservation first = journal.reserve(prepared.id(), Duration.ofMinutes(1));
      assertThatThrownBy(() -> journal.reserve(prepared.id(), Duration.ofMinutes(1))).isInstanceOfSatisfying(UploadJournalException.class,
         e -> assertThat(e.getReason()).isEqualTo(Reason.LEASE_HELD));

      clock.advance(Duration.ofMinutes(2));
      assertThatThrownBy(() -> journal.recordStorage(first, UploadStorageState.UNKNOWN)).isInstanceOfSatisfying(UploadJournalException.class,
         e -> assertThat(e.getReason()).isEqualTo(Reason.STALE_RESERVATION));

      UploadReservation second = journal.reserve(prepared.id(), Duration.ofMinutes(1));
      assertThat(second.fence()).isEqualTo(2L);
      AtomicInteger calls = new AtomicInteger();
      assertThatThrownBy(() -> journal.recordStorage(first, UploadStorageState.VERIFIED)).isInstanceOfSatisfying(UploadJournalException.class,
         e -> assertThat(e.getReason()).isEqualTo(Reason.STALE_RESERVATION));
      assertThatThrownBy(() -> journal.register(first, inserting(calls))).isInstanceOfSatisfying(UploadJournalException.class,
         e -> assertThat(e.getReason()).isEqualTo(Reason.STALE_RESERVATION));
      assertThatThrownBy(() -> journal.complete(first)).isInstanceOf(UploadJournalException.class);
      assertThat(journal.release(first)).isFalse();
      assertThat(calls).hasValue(0);
      assertThat(count("SELECT COUNT(*) FROM collaboration_attachment")).isZero();

      journal.recordStorage(second, UploadStorageState.VERIFIED);
      assertThat(journal.release(second)).isTrue();
      assertThat(journal.find(prepared.id()).orElseThrow().leaseUntil()).isNull();
      assertThat(journal.reserve(prepared.id(), Duration.ofMinutes(1)).fence()).isEqualTo(3L);
   }



   /*******************************************************************************
    ** Renewal extends only the live exact holder and cannot revive expired work.
    *******************************************************************************/
   @Test
   void renewPreservesFenceAndRefusesExpiredOrReplacedHolders() throws Exception
   {
      UploadEntry prepared = journal.prepare(candidate("renew"));
      UploadReservation first = journal.reserve(prepared.id(), Duration.ofMinutes(1));
      clock.advance(Duration.ofSeconds(45));
      UploadReservation renewed = journal.renew(first, Duration.ofMinutes(1));
      assertThat(renewed.fence()).isEqualTo(first.fence());
      clock.advance(Duration.ofSeconds(30));
      journal.recordStorage(renewed, UploadStorageState.VERIFIED);
      clock.advance(Duration.ofMinutes(1));
      assertThatThrownBy(() -> journal.renew(renewed, Duration.ofMinutes(1))).isInstanceOfSatisfying(UploadJournalException.class,
         error -> assertThat(error.getReason()).isEqualTo(Reason.STALE_RESERVATION));
      UploadReservation replacement = journal.reserve(prepared.id(), Duration.ofMinutes(1));
      assertThat(replacement.fence()).isGreaterThan(first.fence());
      assertThatThrownBy(() -> journal.renew(first, Duration.ofMinutes(1))).isInstanceOf(UploadJournalException.class);
      assertThatThrownBy(() -> journal.renew(replacement, Duration.ZERO)).isInstanceOf(IllegalArgumentException.class);
   }

