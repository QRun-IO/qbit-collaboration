   /*******************************************************************************
    ** Prepare a candidate and bring it to a live reservation with VERIFIED storage.
    *******************************************************************************/
   private UploadReservation verified(UploadCandidate candidate) throws QException
   {
      UploadEntry prepared = journal.prepare(candidate);
      UploadReservation reservation = journal.reserve(prepared.id(), Duration.ofMinutes(5));
      journal.recordStorage(reservation, UploadStorageState.UNKNOWN);
      journal.recordStorage(reservation, UploadStorageState.VERIFIED);
      return (reservation);
   }



   /*******************************************************************************
    ** Run the same call on N threads, each with its own QQQ context and connection.
    ** Each outcome is the result or the thrown exception.
    *******************************************************************************/
   private List<Object> race(int threads, Callable<Object> call) throws Exception
   {
      ExecutorService pool = Executors.newFixedThreadPool(threads);
      try
      {
         CountDownLatch start = new CountDownLatch(1);
         List<Future<Object>> futures = new ArrayList<>();
         for(int i = 0; i < threads; i++)
         {
            futures.add(pool.submit(() ->
            {
               initContext(instance);
               start.await();
               try
               {
                  return (call.call());
               }
               catch(UploadJournalException e)
               {
                  return (e);
               }
            }));
         }
         start.countDown();
         List<Object> outcomes = new ArrayList<>();
         for(Future<Object> future : futures)
         {
            outcomes.add(future.get(60, TimeUnit.SECONDS));
         }
         return (outcomes);
      }
      finally
      {
         pool.shutdownNow();
      }
   }



   /*******************************************************************************
    ** A registrar that inserts a stand-in attachment row in the journal's transaction.
    *******************************************************************************/
   private UploadJournal.AttachmentRegistrar inserting(AtomicInteger calls)
   {
      return ((transaction, candidate, journalId) ->
      {
         calls.incrementAndGet();
         return (insertAttachment(transaction, candidate));
      });
   }



   /*******************************************************************************
    ** Insert through the supplied transaction's own connection and return the id.
    *******************************************************************************/
   private static Integer insertAttachment(QBackendTransaction transaction, UploadCandidate candidate) throws QException
   {
      try(PreparedStatement statement = ((RDBMSTransaction) transaction).getConnection()
         .prepareStatement("INSERT INTO collaboration_attachment (file_name) VALUES (?)", Statement.RETURN_GENERATED_KEYS))
      {
         statement.setString(1, candidate.fileName());
         statement.executeUpdate();
         try(ResultSet keys = statement.getGeneratedKeys())
         {
            keys.next();
            return (keys.getInt(1));
         }
      }
      catch(SQLException e)
      {
         throw (new QException("Could not insert the stand-in attachment.", e));
      }
   }



   /*******************************************************************************
    ** Count rows using a separate real connection, so only committed data counts.
    *******************************************************************************/
   private long count(String sql) throws SQLException
   {
      try(Connection connection = DriverManager.getConnection(database.getJdbcUrl(), "sa", ""); Statement statement = connection.createStatement();
         ResultSet result = statement.executeQuery(sql))
      {
         result.next();
         return (result.getLong(1));
      }
   }



